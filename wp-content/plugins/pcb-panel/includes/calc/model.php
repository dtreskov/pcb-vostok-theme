/** Значения по умолчанию: key => value. */
function pcb_calc_defaults() {
	return array_map( function ( $d ) {
		return $d['v'];
	}, pcb_calc_params() );
}

/** Число из ввода: округление до 6 знаков или $fb. */
function pcb_calc_num( $x, $fb ) {
	return is_numeric( $x ) ? round( (float) $x, 6 ) : (float) $fb;
}

/**
 * Кривая к виду {x: [..], y: {row: [..]}}: точки по возрастанию X (от 1 до 12), у всех строк — по числу X.
 * Повтор X и пустые значения отбрасываются; если ничего не осталось — значение по умолчанию.
 */
function pcb_calc_curve_clean( array $d, $v, $old ) {
	$def = $d['v'];
	$old = is_array( $old ) && isset( $old['x'], $old['y'] ) ? $old : $def;
	if ( ! is_array( $v ) || ! isset( $v['x'] ) || ! is_array( $v['x'] ) ) {
		return $old;
	}
	$pts = array();
	foreach ( array_values( $v['x'] ) as $i => $x ) {
		if ( ! is_numeric( $x ) || (float) $x <= ( empty( $d['log'] ) ? -1e12 : 0 ) ) {
			continue;
		}
		$col = array();
		foreach ( $d['rows'] as $rk => $label ) {
			$rk         = (string) $rk;
			$y          = $v['y'][ $rk ][ $i ] ?? null;
			$col[ $rk ] = is_numeric( $y ) ? round( (float) $y, 6 ) : null;
		}
		$pts[ (string) round( (float) $x, 6 ) ] = array( round( (float) $x, 6 ), $col );
	}
	if ( ! $pts ) {
		return $old;
	}
	ksort( $pts, SORT_NUMERIC );
	$pts = array_slice( array_values( $pts ), 0, 12 );
	$out = array( 'x' => array(), 'y' => array() );
	foreach ( $d['rows'] as $rk => $label ) {
		$out['y'][ (string) $rk ] = array();
	}
	foreach ( $pts as $pt ) {
		$out['x'][] = $pt[0];
		foreach ( $pt[1] as $rk => $y ) {
			$prev                 = end( $out['y'][ $rk ] );
			$out['y'][ $rk ][]    = null !== $y ? $y : ( false !== $prev ? $prev : (float) ( $old['y'][ $rk ][0] ?? $def['y'][ $rk ][0] ?? 0 ) );
		}
	}
	return $out;
}

/**
 * Значение кривой в точке $x для строки $row: прямая между соседними точками (по логарифму X, если log),
 * за крайними точками — крайнее значение.
 */
function pcb_calc_curve( array $curve, $row, $x, $log = true ) {
	$xs = $curve['x'] ?? array();
	$ys = $curve['y'][ (string) $row ] ?? null;
	if ( ! $xs || ! $ys ) {
		return null;
	}
	$n = count( $xs );
	if ( $x <= $xs[0] || 1 === $n ) {
		return (float) $ys[0];
	}
	if ( $x >= $xs[ $n - 1 ] ) {
		return (float) $ys[ $n - 1 ];
	}
	for ( $i = 1; $i < $n; $i++ ) {
		if ( $x <= $xs[ $i ] ) {
			$a = $xs[ $i - 1 ];
			$b = $xs[ $i ];
			$t = $log && $a > 0 ? ( log( $x ) - log( $a ) ) / ( log( $b ) - log( $a ) ) : ( $x - $a ) / ( $b - $a );
			return (float) $ys[ $i - 1 ] + ( (float) $ys[ $i ] - (float) $ys[ $i - 1 ] ) * $t;
		}
	}
	return (float) $ys[ $n - 1 ];
}

/** Строка ступенчатой таблицы по верхней границе («до N»): первая строка с границей ≥ $x, иначе последняя. */
function pcb_calc_step( array $table, $x ) {
	foreach ( $table as $lim => $v ) {
		if ( 'inf' === (string) $lim || $x <= (float) $lim ) {
			return (float) $v;
		}
	}
	return (float) end( $table );
}

/**
 * Приводит присланные значения к типам модели. Неизвестные ключи отбрасываются, недостающие — из $base.
 * Значения вне min…max сохраняются (менеджер может быть посреди ввода), но попадают в pcb_calc_errors().
 * Значение старого типа (например, число вместо таблицы после обновления плагина) заменяется значением по умолчанию.
 */
function pcb_calc_clean( $in, array $base = null ) {
	$base = $base ?? pcb_calc_defaults();
	$out  = array();
	foreach ( pcb_calc_params() as $k => $d ) {
		$has = is_array( $in ) && array_key_exists( $k, $in );
		$v   = $has ? $in[ $k ] : ( $base[ $k ] ?? $d['v'] );
		switch ( $d['t'] ) {
			case 'bool':
				$out[ $k ] = (bool) $v && 'false' !== $v && '0' !== $v;
				break;
			case 'sel':
				$v         = (string) $v;
				$out[ $k ] = isset( $d['opts'][ $v ] ) ? $v : $d['v'];
				break;
			case 'text':
				$out[ $k ] = is_scalar( $v ) ? mb_substr( trim( wp_strip_all_tags( (string) $v ) ), 0, 120 ) : $d['v'];
				break;
			case 'table':
				$row = array();
				$src = is_array( $v ) ? $v : array();
				$old = is_array( $base[ $k ] ?? null ) ? $base[ $k ] : $d['v'];
				foreach ( $d['rows'] as $rk => $label ) {
					$rk         = (string) $rk;
					$fb         = $old[ $rk ] ?? $d['v'][ $rk ];
					$row[ $rk ] = pcb_calc_num( is_array( $src[ $rk ] ?? null ) ? null : ( $src[ $rk ] ?? null ), is_numeric( $fb ) ? $fb : $d['v'][ $rk ] );
				}
				$out[ $k ] = $row;
				break;
			case 'grid':
				$src = is_array( $v ) ? $v : array();
				$old = is_array( $base[ $k ] ?? null ) ? $base[ $k ] : $d['v'];
				$g   = array();
				foreach ( $d['rows'] as $rk => $label ) {
					$rk = (string) $rk;
					$sr = is_array( $src[ $rk ] ?? null ) ? $src[ $rk ] : array(); // старое значение другого типа — не таблица
					$or = is_array( $old[ $rk ] ?? null ) ? $old[ $rk ] : array();
					foreach ( $d['cols'] as $ck => $cl ) {
						$fb             = $or[ $ck ] ?? $d['v'][ $rk ][ $ck ];
						$g[ $rk ][ $ck ] = pcb_calc_num( $sr[ $ck ] ?? null, is_numeric( $fb ) ? $fb : $d['v'][ $rk ][ $ck ] );
					}
				}
				$out[ $k ] = $g;
				break;
			case 'curve':
				$out[ $k ] = pcb_calc_curve_clean( $d, $v, $base[ $k ] ?? null );
				break;
			default:
				$fb        = $base[ $k ] ?? $d['v'];
				$out[ $k ] = pcb_calc_num( is_array( $v ) ? null : $v, is_numeric( $fb ) ? $fb : $d['v'] );
		}
	}
	return $out;
}

/** Ошибки диапазонов: key[.row] => текст. Пустой массив — можно публиковать. */
function pcb_calc_errors( array $p ) {
	$err = array();
	foreach ( pcb_calc_params() as $k => $d ) {
		if ( 'table' === $d['t'] ) {
			foreach ( $p[ $k ] as $rk => $x ) {
				if ( $x < 0 || $x > 1e7 ) {
					$err[ $k . '.' . $rk ] = $d['n'] . ', ' . $d['rows'][ $rk ] . ': значение вне допустимого';
				}
			}
			continue;
		}
		if ( 'grid' === $d['t'] ) {
			foreach ( $p[ $k ] as $rk => $cols ) {
				foreach ( $cols as $ck => $x ) {
					if ( ( empty( $d['neg'] ) && $x < 0 ) || abs( $x ) > 1e7 ) {
						$err[ $k . '.' . $rk . '.' . $ck ] = $d['n'] . ', ' . $d['rows'][ $rk ] . ', ' . mb_strtolower( $d['cols'][ $ck ] ) . ': значение вне допустимого';
					}
				}
			}
			continue;
		}
		if ( 'curve' === $d['t'] ) {
			foreach ( $p[ $k ]['y'] as $rk => $ys ) {
				foreach ( $ys as $y ) {
					if ( $y < 0 || $y > 1e7 ) {
						$err[ $k . '.' . $rk ] = $d['n'] . ', ' . $d['rows'][ $rk ] . ': значение вне допустимого';
						break;
					}
				}
			}
			continue;
		}
		if ( isset( $d['min'] ) && ( $p[ $k ] < $d['min'] || $p[ $k ] > $d['max'] ) ) {
			$err[ $k ] = $d['n'] . ': допустимо от ' . $d['min'] . ' до ' . $d['max'];
		}
	}
	if ( isset( $p['termStd'] ) && '' === $p['termStd'] ) {
		$err['termStd'] = 'Срок на сайте не может быть пустым';
	}
	foreach ( array( 'cnyFrom', 'cnyTo' ) as $k ) {
		if ( isset( $p[ $k ] ) && '' !== $p[ $k ] && ! preg_match( '/^\d{4}-\d{2}-\d{2}$/', $p[ $k ] ) ) {
			$err[ $k ] = pcb_calc_params()[ $k ]['n'] . ': дата в виде ГГГГ-ММ-ДД или пусто';
		}
	}
	return $err;
}

/**
 * Мягкие предупреждения: не блокируют публикацию, подсказывают, где значения выглядят странно.
 * [{k, row, lvl: red|yellow, t}] — red: цена ведёт себя нелогично; yellow: необычно, стоит проверить.
 */
function pcb_calc_soft( array $p ) {
	$out = array();
	$add = function ( $k, $row, $lvl, $t ) use ( &$out ) {
		$out[] = array( 'k' => $k, 'row' => (string) $row, 'lvl' => $lvl, 't' => $t );
	};
	$nf  = function ( $x ) {
		return pcb_calc_n( $x );
	};
	foreach ( pcb_calc_params() as $k => $d ) {
		if ( isset( $d['soft'] ) && is_numeric( $p[ $k ] ?? null ) && ( $p[ $k ] < $d['soft'][0] || $p[ $k ] > $d['soft'][1] ) ) {
			$add( $k, '', 'yellow', 'Обычно от ' . $nf( $d['soft'][0] ) . ' до ' . $nf( $d['soft'][1] ) . ' — проверьте значение.' );
		}
		if ( 'curve' !== $d['t'] ) {
			continue;
		}
		$c   = $p[ $k ];
		$xs  = $c['x'];
		$log = ! empty( $d['log'] );
		// проба по сетке между точками: цена партии (x × y) или цена с наценкой (x × (1 + y %)) не должна падать
		if ( ! empty( $d['mono'] ) && count( $xs ) > 1 ) {
			$grid = array();
			for ( $i = 0; $i < count( $xs ) - 1; $i++ ) {
				for ( $j = 0; $j < 8; $j++ ) {
					$t      = $j / 8;
					$grid[] = $log ? exp( log( $xs[ $i ] ) + ( log( $xs[ $i + 1 ] ) - log( $xs[ $i ] ) ) * $t ) : $xs[ $i ] + ( $xs[ $i + 1 ] - $xs[ $i ] ) * $t;
				}
			}
			$grid[] = end( $xs );
			foreach ( $d['rows'] as $rk => $label ) {
				$prev = null;
				foreach ( $grid as $x ) {
					$y   = pcb_calc_curve( $c, $rk, $x, $log );
					$tot = 'margin' === $d['mono'] ? $x * ( 1 + $y / 100 ) : $x * $y;
					if ( null !== $prev && $tot < $prev[1] * 0.999 ) {
						$add( $k, $rk, 'red', $label . ': при ' . $nf( $x ) . ' ' . $d['xu'] . ' итог меньше, чем при ' . $nf( $prev[0] ) . ' ' . $d['xu'] . ' — больший заказ обойдётся клиенту дешевле меньшего.' );
						break;
					}
					$prev = array( $x, $tot );
				}
			}
		}
		// больше слоёв не должно быть дешевле меньшего числа слоёв
		if ( ! empty( $d['order'] ) ) {
			$keys = array_keys( $d['rows'] );
			foreach ( $xs as $i => $x ) {
				for ( $r = 1; $r < count( $keys ); $r++ ) {
					$a = $c['y'][ (string) $keys[ $r - 1 ] ][ $i ];
					$b = $c['y'][ (string) $keys[ $r ] ][ $i ];
					if ( $b < $a ) {
						$add( $k, $keys[ $r ], 'yellow', $d['rows'][ $keys[ $r ] ] . ' дешевле, чем ' . $d['rows'][ $keys[ $r - 1 ] ] . ', при ' . $nf( $x ) . ' ' . $d['xu'] . ' — проверьте прайс.' );
					}
				}
			}
		}
		// резкий скачок между соседними точками (в 2 и более раза) — у ставок, тарифов и наценки; сборы могут падать до нуля
		foreach ( empty( $d['mono'] ) ? array() : $d['rows'] as $rk => $label ) {
			$ys = $c['y'][ (string) $rk ];
			for ( $i = 1; $i < count( $ys ); $i++ ) {
				$a = $ys[ $i - 1 ];
				$b = $ys[ $i ];
				if ( $a > 0 && $b > 0 && max( $a, $b ) / min( $a, $b ) >= 2 ) {
					$add( $k, $rk, 'yellow', $label . ': между ' . $nf( $xs[ $i - 1 ] ) . ' и ' . $nf( $xs[ $i ] ) . ' ' . $d['xu'] . ' значение меняется в ' . $nf( max( $a, $b ) / min( $a, $b ) ) . ' раза — проверьте точки.' );
				}
			}
		}
	}
	if ( ( $p['fineTrack'] ?? 0 ) <= ( $p['minTrack'] ?? 0 ) ) {
		$add( 'fineTrack', '', 'yellow', 'Порог тонкой дорожки не больше порога расчёта инженером — надбавка за тонкую дорожку не сработает никогда.' );
	}
	if ( ( $p['bandMin'] ?? 0 ) > ( $p['band']['base']['lo'] ?? 0 ) ) {
		$add( 'bandMin', '', 'yellow', 'Ограничение вилки снизу меньше базовой строки — базовая вилка обрезается.' );
	}
	return $out;
}

/** Подписи изменённых параметров между двумя наборами. */
function pcb_calc_diff( array $a, array $b ) {
	$out = array();
	foreach ( pcb_calc_params() as $k => $d ) {
		if ( wp_json_encode( $a[ $k ] ?? null ) !== wp_json_encode( $b[ $k ] ?? null ) ) {
			$out[] = $d['n'];
		}
	}
	return $out;
}

